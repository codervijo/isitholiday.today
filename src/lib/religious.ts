const lastDay = (o: Observance) => o.end ?? o.date;

export const observancesOn = (d: string) => OBSERVANCES.filter((o) => o.date <= d && d <= lastDay(o));

/** Sundown-faith observances starting tomorrow: they begin this evening. */
export const beginningTonight = (today: string, tomorrow: string) =>
  OBSERVANCES.filter((o) => FAITHS[o.faith].sundown && o.date === tomorrow && !observancesOn(today).includes(o));

export const upcomingObservances = (from: string, limit = 10) =>
  [...OBSERVANCES].filter((o) => o.date > from).sort((a, b) => a.date.localeCompare(b.date)).slice(0, limit);

/** "day 3 of 8" for multi-day observances. */
export function dayOf(o: Observance, d: string): string | null {
  if (!o.end) return null;
  const n = (a: string, b: string) => Math.round((Date.parse(b) - Date.parse(a)) / 86_400_000);
  return `day ${n(o.date, d) + 1} of ${n(o.date, o.end) + 1}`;
}

export const findObservance = (faith: Faith, name: RegExp, year: string) =>
  OBSERVANCES.find((o) => o.faith === faith && name.test(o.name) && o.date.startsWith(year)) ?? null;
